import { AGENT_HEADER } from './mail/mime';
import { InboundMail } from './mail/provider';
import { normalizeAddress } from './ea-db';

/** Rules that run before any AI, and keep running when the AI is off, paused or over budget. */

export type TriageResult =
  | 'own_mail' | 'bounce' | 'auto_generated' | 'unsubscribe' | 'suppressed_sender' | 'pass';

export interface ParsedFrom { address: string; name: string; }

export function parseFrom(raw: string | undefined): ParsedFrom {
  const value = (raw || '').trim();
  const angle = value.match(/^(.*)<([^<>]+)>\s*$/);
  if (angle) return { name: angle[1].trim().replace(/^"|"$/g, ''), address: normalizeAddress(angle[2]) };
  const plain = value.match(/[^\s<>,;]+@[^\s<>,;]+/);
  return { name: '', address: normalizeAddress(plain?.[0] ?? '') };
}

/** Removes HTML to plain text for messages with no text part; the result is only ever treated as untrusted data. */
export function htmlToText(html: string): string {
  return html
    .replace(/<(script|style|head)[\s\S]*?<\/\1>/gi, ' ')
    .replace(/<!--[\s\S]*?-->/g, ' ')
    .replace(/<(br|\/p|\/div|\/tr|\/li|\/h\d)\b[^>]*>/gi, '\n')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/g, ' ').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&amp;/g, '&')
    .replace(/[ \t]+/g, ' ')
    .replace(/\n\s*\n\s*\n+/g, '\n\n')
    .trim();
}

const QUOTE_MARKERS: RegExp[] = [
  /^\s*On .{5,200}wrote:\s*$/i,
  /^\s*-{2,}\s*(Original|Forwarded) Message\s*-{2,}\s*$/i,
  /^\s*_{10,}\s*$/,
  /^\s*From:\s.+$/i,
  /^\s*Sent from my \w+/i,
  /^\s*\d{4}[-/.]\d{1,2}[-/.]\d{1,2}.{0,60}wrote:\s*$/i,
];

/** Quoted history can hide old text or injected instructions, so analysis only ever sees what the sender just wrote. */
export function stripQuotedHistory(text: string): string {
  const out: string[] = [];
  for (const line of (text || '').replace(/\r\n/g, '\n').split('\n')) {
    if (QUOTE_MARKERS.some(re => re.test(line))) break;
    if (/^\s*>/.test(line)) continue;
    out.push(line);
  }
  return out.join('\n').trim();
}

const AUTO_PRECEDENCE = /^(bulk|list|junk|auto[_-]?reply)$/i;

export function isAutoGenerated(headers: Record<string, string>): boolean {
  const autoSubmitted = (headers['auto-submitted'] || '').trim().toLowerCase();
  if (autoSubmitted && autoSubmitted !== 'no') return true;
  if (AUTO_PRECEDENCE.test((headers['precedence'] || '').trim())) return true;
  if (headers['list-id']) return true;
  return false;
}

const BOUNCE_FROM = /^(mailer-daemon|postmaster|mail-daemon|bounces?)(\+[^@]*)?@/i;

export function isBounce(mail: InboundMail, fromAddress: string): boolean {
  const contentType = (mail.headers['content-type'] || '').toLowerCase();
  if (contentType.includes('multipart/report') && contentType.includes('delivery-status')) return true;
  if (mail.headers['x-failed-recipients']) return true;
  return BOUNCE_FROM.test(fromAddress);
}

/** Addresses a bounce says failed. Only these can be suppressed, and only if we actually wrote to them. */
export function bouncedAddresses(mail: InboundMail): string[] {
  const found = new Set<string>();
  const add = (v?: string) => {
    for (const m of (v || '').matchAll(/[a-z0-9._%+'-]+@[a-z0-9-]+(?:\.[a-z0-9-]+)*\.[a-z]{2,}/gi)) found.add(normalizeAddress(m[0]));
  };
  add(mail.headers['x-failed-recipients']);
  for (const m of (mail.reportText || '').matchAll(/^(?:Final|Original)-Recipient:\s*(?:rfc822;)?\s*(.+)$/gim)) add(m[1]);
  if (!found.size) {
    for (const m of (mail.text || '').matchAll(/(?:wasn't delivered to|could not be delivered to|delivery to the following recipient[s]? failed[^:]*:?)\s*([^\s]+@[^\s]+)/gi)) add(m[1]);
  }
  return [...found];
}

const UNSUBSCRIBE_LINE = [
  /^\s*(please\s+)?(unsubscribe|stop|opt[\s-]?out|remove)(\s+me)?\s*[.!]?\s*$/i,
  /\b(please\s+)?unsubscribe\s+me\b/i,
  /\b(please\s+)?remove\s+me\s+from\s+(your|the|this)\b/i,
  /\bi\s+(want|wish|would like)\s+to\s+(unsubscribe|opt[\s-]?out)\b/i,
  /\b(stop|don'?t|do not)\s+(e-?mail(ing)?|contact(ing)?|mail(ing)?|writ(e|ing) to)\s+me\b/i,
  // Sinhala and Tamil: "don't send", "remove from the list"
  /එවන්න\s*එපා|ඉවත්\s*කරන්න/,
  /அனுப்ப\s*வேண்டாம்|நீக்கவும்/,
];

export function isUnsubscribeRequest(subject: string, cleanBody: string): boolean {
  if (/^\s*(re:\s*)*(unsubscribe|opt[\s-]?out|stop)\s*$/i.test(subject || '')) return true;
  // Only the sender's own first lines count: a long message that mentions the word is left for the AI to weigh
  const lines = (cleanBody || '').split('\n').map(l => l.trim()).filter(Boolean).slice(0, 5);
  return lines.some(line => UNSUBSCRIBE_LINE.some(re => re.test(line)));
}

export function triage(mail: InboundMail, from: ParsedFrom, ownAddress: string, cleanBody: string, senderSuppressed: boolean): TriageResult {
  // Our own mail comes first: an alert or copy of a sent message must never go further, even one that looks like a bounce
  if (mail.headers[AGENT_HEADER.toLowerCase()] || (ownAddress && from.address === ownAddress) || mail.labelIds.includes('SENT')) return 'own_mail';
  if (isBounce(mail, from.address)) return 'bounce';
  if (isAutoGenerated(mail.headers)) return 'auto_generated';
  if (isUnsubscribeRequest(mail.headers['subject'] || '', cleanBody)) return 'unsubscribe';
  if (senderSuppressed) return 'suppressed_sender';
  return 'pass';
}

const INJECTION_PATTERNS: RegExp[] = [
  /\bignore\s+(all\s+|any\s+)?(the\s+)?(previous|prior|above|earlier|your)\s+(instructions?|prompts?|rules?)/i,
  /\bdisregard\s+(all\s+|any\s+)?(the\s+)?(previous|prior|above|your)\b/i,
  /\b(system|developer)\s*(prompt|message|instructions?)\b/i,
  /\byou\s+are\s+now\b/i,
  /\b(reveal|print|show|repeat)\s+(your|the)\s+(prompt|instructions|system)/i,
  /\b(approve|send)\s+(this|the)\s+(email|draft|reply)\s+(immediately|automatically|without)/i,
  /<\/?(system|assistant|untrusted_[a-z]+)\b/i,
  /\bnew\s+instructions?\s*:/i,
];

export function looksLikeInjection(text: string): boolean {
  return INJECTION_PATTERNS.some(re => re.test(text || ''));
}

/** Script-based only: decides the reply language when the sender used Sinhala or Tamil. */
export function detectLanguage(text: string): 'en' | 'si' | 'ta' {
  const si = (text.match(/[඀-෿]/g) || []).length;
  const ta = (text.match(/[஀-௿]/g) || []).length;
  if (si === 0 && ta === 0) return 'en';
  return si >= ta ? 'si' : 'ta';
}
