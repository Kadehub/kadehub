describe('tokens', () => {
  const env = { ...process.env };
  afterEach(() => { process.env = { ...env }; });

  it('worker token: constant-time check, 24+ characters required', () => {
    process.env.EMAIL_AGENT_WORKER_TOKEN = 'short';
    expect(workerTokenValid('short')).toBe(false);
    process.env.EMAIL_AGENT_WORKER_TOKEN = 'x'.repeat(32);
    expect(workerTokenValid('x'.repeat(32))).toBe(true);
    expect(workerTokenValid('y'.repeat(32))).toBe(false);
    expect(workerTokenValid(undefined)).toBe(false);
    delete process.env.EMAIL_AGENT_WORKER_TOKEN;
    expect(workerTokenValid('')).toBe(false);
  });

  it('unsubscribe link is bound to one address and goes in the query string', () => {
    process.env.EMAIL_AGENT_UNSUBSCRIBE_SECRET = 'z'.repeat(32);
    const token = unsubscribeToken('A@Shop.lk');
    expect(verifyUnsubscribeToken(token)).toBe('a@shop.lk');
    const forged = `${Buffer.from('other@shop.lk').toString('base64url')}.${token.split('.')[1]}`;
    expect(verifyUnsubscribeToken(forged)).toBeNull();
    expect(verifyUnsubscribeToken('junk')).toBeNull();
    expect(unsubscribeUrl('a@shop.lk')).toContain('/email-agent/unsubscribe?t=');
    delete process.env.EMAIL_AGENT_UNSUBSCRIBE_SECRET;
    expect(verifyUnsubscribeToken(token)).toBeNull();
  });
});
