import { Type } from 'class-transformer';
import { IsBoolean, IsIn, IsNumber, IsOptional, IsString, Matches, MaxLength, Max, Min, ValidateIf } from 'class-validator';

/** Business categories offered for new expenses (older rows may carry other names and keep working). */
export const BUSINESS_EXPENSE_CATEGORIES = [
  'Supplier', 'Shipping', 'Customs', 'Advertising', 'Salary', 'Rent', 'Packaging', 'Utilities', 'Business Tour', 'Misc', 'Other',
] as const;

export const PERSONAL_EXPENSE_CATEGORIES = [
  'Personal', 'Investment', 'Alcohol', 'Sports', 'Outings', 'PickMe', 'Fuel', 'Other',
] as const;

export const PAYMENT_METHODS = ['cash', 'bank', 'card', 'cheque', 'other'] as const;

export const MAX_EXPENSE_AMOUNT = 100_000_000;
const YMD = /^\d{4}-\d{2}-\d{2}$/;

export class SaveBusinessExpenseDto {
  /** Optional: blank means "use the category name". */
  @IsOptional() @IsString() @MaxLength(255) title?: string;
  /** Free text so existing rows with older category names can still be edited; new rows use the tiles. */
  @IsString() @MaxLength(100) category: string;
  @Type(() => Number) @IsNumber() @Min(0.01) @Max(MAX_EXPENSE_AMOUNT) amount: number;
  @Matches(YMD, { message: 'EXPENSE_DATE' }) expense_date: string;
  @IsOptional() @IsIn(PAYMENT_METHODS as unknown as string[]) payment_method?: string | null;
  @IsOptional() @IsString() @MaxLength(150) vendor?: string | null;
  @IsOptional() @IsString() @MaxLength(100) reference?: string | null;
  @IsOptional() @IsString() @MaxLength(2000) notes?: string | null;
  /** Second send after the user confirmed "Yes, add it" on the lookalike warning. */
  @IsOptional() @IsBoolean() allow_duplicate?: boolean;
}

export class SavePersonalExpenseDto {
  @IsIn(PERSONAL_EXPENSE_CATEGORIES as unknown as string[]) category: string;
  @Type(() => Number) @IsNumber() @Min(0.01) @Max(MAX_EXPENSE_AMOUNT) amount: number;
  @Matches(YMD, { message: 'EXPENSE_DATE' }) expense_date: string;
  @IsOptional() @IsIn(PAYMENT_METHODS as unknown as string[]) payment_method?: string | null;
  @IsOptional() @IsString() @MaxLength(500) note?: string | null;
  /** Generated by the browser each time the sheet opens. */
  @IsOptional() @Matches(/^[0-9a-f-]{36}$/i, { message: 'client_ref must be a UUID' }) client_ref?: string;
  @IsOptional() @IsBoolean() allow_duplicate?: boolean;
}

export class PersonalSettingsDto {
  /** null removes the budget. */
  @ValidateIf((_, v) => v !== null)
  @Type(() => Number) @IsNumber() @Min(1) @Max(MAX_EXPENSE_AMOUNT)
  monthly_budget: number | null;
}

export class ExpenseRangeQuery {
  @IsOptional() @Matches(YMD) from?: string;
  @IsOptional() @Matches(YMD) to?: string;
}
