const decodeBody = (raw: Buffer) => {
  const text = raw.toString('utf8');
  const b64 = text.split('Content-Transfer-Encoding: base64\r\n\r\n')[1].split('\r\n--')[0];
  return Buffer.from(b64.replace(/\r\n/g, ''), 'base64').toString('utf8');
};

describe('MIME building', () => {
  const base = { from: 'hello@kadehub.com', to: 'shop@example.lk', subject: 'Hello', body: 'Body', messageId: '<a@kadehub.com>' };

  it('refuses header injection in every header value', () => {
    expect(() => buildRfc822({ ...base, subject: 'Hi\r\nBcc: evil@x.com' })).toThrow(HeaderInjectionError);
    expect(() => buildRfc822({ ...base, inReplyTo: '<a>\nBcc: evil@x.com' })).toThrow(HeaderInjectionError);
    expect(() => buildRfc822({ ...base, references: '<a>\r\nX: y' })).toThrow(HeaderInjectionError);
    expect(() => buildRfc822({ ...base, to: 'a@b.com\r\nBcc: e@x.com' })).toThrow(HeaderInjectionError);
    expect(() => buildRfc822({ ...base, fromName: 'K\nBcc: e@x.com' })).toThrow(HeaderInjectionError);
    expect(() => buildRfc822({ ...base, subject: 'Hi\u2028Bcc: e@x.com' })).toThrow(HeaderInjectionError);
  });

  it('rejects addresses that smuggle extra recipients', () => {
    for (const bad of ['a@b.com, c@d.com', 'a@b.com;c@d.com', 'A <a@b.com>', 'a b@c.com', 'not-an-email', '']) expect(isValidAddress(bad)).toBe(false);
    expect(isValidAddress("o'brien+tag@shop.example.lk")).toBe(true);
  });

  it('encodes non-ASCII subjects without cutting a character, and base64 UTF-8 bodies', () => {
    const subject = 'ඔබේ ව්‍යාපාරය සඳහා KadeHub POS පද්ධතිය ගැන තොරතුරු';
    const raw = buildRfc822({ ...base, subject, body: 'ආයුබෝවන්\nவணக்கம்' });
    const header = raw.toString('utf8').match(/Subject: ([\s\S]*?)\r\nMessage-ID/)[1];
    expect(header).not.toMatch(/[^\x00-\x7f]/);
    const words = header.split('\r\n ').map(w => Buffer.from(w.replace(/^=\?UTF-8\?B\?|\?=$/g, ''), 'base64').toString('utf8'));
    expect(words.join('')).toBe(subject);
    expect(words.join('')).not.toContain('\uFFFD');
    expect(decodeBody(raw)).toBe('ආයුබෝවන්\r\nவணக்கம்');
  });

  it('sets threading, the agent header and List-Unsubscribe', () => {
    const text = buildRfc822({
      ...base, inReplyTo: '<p@x>', references: '<o@x> <p@x>',
      listUnsubscribe: { url: 'https://api.kadehub.com/api/email-agent/unsubscribe?t=abc', mailto: 'hello@kadehub.com' },
    }).toString('utf8');
    expect(text).toContain('In-Reply-To: <p@x>\r\n');
    expect(text).toContain('References: <o@x> <p@x>\r\n');
    expect(text).toContain(`${AGENT_HEADER}: outbound\r\n`);
    expect(text).toContain('List-Unsubscribe: <https://api.kadehub.com/api/email-agent/unsubscribe?t=abc>, <mailto:hello@kadehub.com?subject=unsubscribe>');
    expect(text).toContain('List-Unsubscribe-Post: List-Unsubscribe=One-Click');
  });

  it('builds multipart with safe, encoded filenames', () => {
    const text = buildRfc822({
      ...base,
      attachments: [{ filename: '../../etc/ප්‍රකාශය "x".pdf', contentType: 'application/pdf', content: Buffer.from('%PDF') }],
    }).toString('utf8');
    expect(text).toContain('Content-Type: multipart/mixed; boundary="');
    expect(text).toContain("filename*=UTF-8''");
    expect(text).not.toContain('../');
    expect(text).toContain(Buffer.from('%PDF').toString('base64'));
    expect(() => buildRfc822({ ...base, attachments: [{ filename: 'a.exe', contentType: 'application/x-msdownload', content: Buffer.from('x') }] })).toThrow();
  });

  it('cleans filenames', () => {
    expect(safeFilename('C:\\Users\\me\\report.pdf')).toBe('report.pdf');
    expect(safeFilename('..\\..\\.htaccess')).toBe('htaccess');
    expect(safeFilename('a\r\nb".pdf')).toBe('ab.pdf');
    expect(safeFilename('')).toBe('attachment');
    expect(safeFilename(`${'x'.repeat(300)}.pdf`).endsWith('.pdf')).toBe(true);
    expect(safeFilename(`${'x'.repeat(300)}.pdf`).length).toBeLessThanOrEqual(150);
  });

  it('leaves plain ASCII subjects alone', () => expect(encodeHeaderText('Plain subject')).toBe('Plain subject'));

  it('hash changes with every part, and fields cannot run together', () => {
    const h = contentHash('a', 'b', 'c', 'd');
    expect(contentHash('x', 'b', 'c', 'd')).not.toBe(h);
    expect(contentHash('a', 'x', 'c', 'd')).not.toBe(h);
    expect(contentHash('a', 'b', 'x', 'd')).not.toBe(h);
    expect(contentHash('a', 'b', 'c', 'x')).not.toBe(h);
    expect(contentHash('ab', '', 'c', 'd')).not.toBe(contentHash('a', 'b', 'c', 'd'));
  });
});

describe('Gmail credentials', () => {
  const env = { ...process.env };
  afterEach(() => { process.env = { ...env }; jest.restoreAllMocks(); });

  beforeEach(() => {
    process.env.GMAIL_OAUTH_CLIENT_ID = 'cid';
    process.env.GMAIL_OAUTH_CLIENT_SECRET = 'SECRET_CLIENT';
    process.env.GMAIL_READ_REFRESH_TOKEN = 'READ_ONLY_TOKEN';
    process.env.GMAIL_SEND_REFRESH_TOKEN = 'SEND_ONLY_TOKEN';
    process.env.EMAIL_AGENT_MAILBOX = 'hello@kadehub.com';
  });

  it('the reader only uses the read token and the sender only the send token', async () => {
    const post = jest.spyOn(axios, 'post').mockImplementation(async (url: string, body: any) => {
      if (url.includes('oauth2')) return { data: { access_token: 'short', expires_in: 3600 } } as any;
      return { data: { id: 'x', threadId: 't' } } as any;
    });
    jest.spyOn(axios, 'get').mockResolvedValue({ data: { historyId: 5 } } as any);
    await new GmailReader().getProfileHistoryId();
    expect(String(post.mock.calls[0][1])).toContain('READ_ONLY_TOKEN');
    expect(String(post.mock.calls[0][1])).not.toContain('SEND_ONLY_TOKEN');
    post.mockClear();
    await new GmailSender().send(Buffer.from('raw'), 't');
    expect(String(post.mock.calls[0][1])).toContain('SEND_ONLY_TOKEN');
    expect(String(post.mock.calls[0][1])).not.toContain('READ_ONLY_TOKEN');
  });

  it('errors never carry tokens or request details', async () => {
    jest.spyOn(axios, 'post').mockImplementation(async (url: string) => {
      if (url.includes('oauth2')) return { data: { access_token: 'ACCESS_SECRET', expires_in: 3600 } } as any;
      throw Object.assign(new Error('Request failed Bearer ACCESS_SECRET'), {
        config: { headers: { Authorization: 'Bearer ACCESS_SECRET' } },
        response: { status: 403, data: { error: { message: 'Insufficient permission' } } },
      });
    });
    const err = await new GmailSender().send(Buffer.from('raw')).catch(e => e);
    expect(err).toBeInstanceOf(ProviderError);
    expect(err.definite).toBe(true);
    expect(JSON.stringify({ m: err.message, ...err })).not.toContain('ACCESS_SECRET');
    expect(err.config).toBeUndefined();
  });

  it('5xx and network errors are not treated as a definite refusal', async () => {
    let status: number | undefined = 503;
    jest.spyOn(axios, 'post').mockImplementation(async (url: string) => {
      if (url.includes('oauth2')) return { data: { access_token: 'a', expires_in: 3600 } } as any;
      throw Object.assign(new Error('x'), status ? { response: { status, data: {} } } : { code: 'ETIMEDOUT' });
    });
    const sender = new GmailSender();
    expect((await sender.send(Buffer.from('r')).catch(e => e)).definite).toBe(false);
    status = undefined;
    expect((await sender.send(Buffer.from('r')).catch(e => e)).definite).toBe(false);
  });
});

